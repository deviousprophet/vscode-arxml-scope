#!/usr/bin/env node
/**
 * Generates a synthetic ECUC-Values sample set for manual checks and performance work.
 *
 *   npm run samples:ecuc
 *   node scripts/generate-samples.js [output-dir]
 *
 * Default output is `../sample` from the repository root, i.e. `D:\workspace\sample` on this
 * machine. The files are synthetic, live outside the repository, and are not committed. The
 * generator itself is committed so the set is reproducible. No dependency, no random data.
 */
'use strict';

const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const DEFAULT_OUT = path.resolve(ROOT, '..', 'sample');
const OUT = path.resolve(process.argv[2] || DEFAULT_OUT);
const ARXML_OUT = path.join(OUT, 'arxml');
const FIXTURES = path.join(ROOT, 'src', 'test', 'fixtures');

const PARAMS = [
	{ name: 'Alpha', kind: 'numeric' },
	{ name: 'Beta', kind: 'textual' },
	{ name: 'Gamma', kind: 'boolean' },
	{ name: 'Delta', kind: 'numeric' },
	{ name: 'Epsilon', kind: 'textual' },
	{ name: 'Zeta', kind: 'numeric' },
	{ name: 'Eta', kind: 'boolean' },
	{ name: 'Theta', kind: 'textual' },
	{ name: 'Iota', kind: 'numeric' },
	{ name: 'Kappa', kind: 'textual' },
];

function indent(depth) {
	return '  '.repeat(depth);
}

function parameterXml(container, parameter, index) {
	const pathBase = `/PkgSample/DemoDefs/DemoMod/${container}`;
	const definition = `${pathBase}/${parameter.name}`;
	const value =
		parameter.kind === 'boolean'
			? index % 2 === 0
				? 'true'
				: 'false'
			: parameter.kind === 'textual'
				? parameter.name === 'Epsilon'
					? `a longer textual value for ${container} and the ellipsis check`
					: `text-${container.replace(/\D/g, '')}-${index}`
				: String((Number(container.replace(/\D/g, '')) * 10 + index) % 100000);
	const tag = parameter.kind === 'textual' ? 'ECUC-TEXTUAL-PARAM-VALUE' : 'ECUC-NUMERICAL-PARAM-VALUE';
	const dest = parameter.kind === 'textual' ? 'ECUC-STRING-PARAM-DEF' : 'ECUC-INTEGER-PARAM-DEF';
	const pad = indent(8);
	return [
		`${pad}<${tag}>`,
		`${pad}  <DEFINITION-REF DEST="${dest}">${definition}</DEFINITION-REF>`,
		`${pad}  <VALUE>${value}</VALUE>`,
		`${pad}</${tag}>`,
	];
}

function moduleXml({ containers, paramsPer }) {
	const lines = [
		'<?xml version="1.0" encoding="UTF-8"?>',
		'<!-- Synthetic ECUC sample generated by scripts/generate-samples.js. Not customer data. -->',
		'<AUTOSAR xmlns="http://autosar.org/schema/r4.0" xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance" xsi:schemaLocation="http://autosar.org/schema/r4.0 AUTOSAR_00048.xsd">',
		indent(1) + '<AR-PACKAGES>',
		indent(2) + '<AR-PACKAGE>',
		indent(3) + '<SHORT-NAME>PkgSample</SHORT-NAME>',
		indent(3) + '<ELEMENTS>',
		indent(4) + '<ECUC-MODULE-CONFIGURATION-VALUES>',
		indent(5) + '<SHORT-NAME>DemoMod</SHORT-NAME>',
		indent(5) + '<DEFINITION-REF DEST="ECUC-MODULE-DEF">/PkgSample/DemoDefs/DemoMod</DEFINITION-REF>',
		indent(5) + '<CONTAINERS>',
	];

	for (let at = 1; at <= containers; at++) {
		const id = `Cont${String(at).padStart(4, '0')}`;
		lines.push(indent(6) + '<ECUC-CONTAINER-VALUE>');
		lines.push(indent(7) + `<SHORT-NAME>${id}</SHORT-NAME>`);
		lines.push(
			indent(7) +
				`<DEFINITION-REF DEST="ECUC-PARAM-CONF-CONTAINER-DEF">/PkgSample/DemoDefs/DemoMod/${id}</DEFINITION-REF>`
		);
		if (at % 25 === 0) {
			lines.push(indent(7) + '<ANNOTATIONS>');
			lines.push(indent(8) + '<ANNOTATION>');
			lines.push(indent(9) + '<ANNOTATION-TEXT>');
			lines.push(indent(10) + '<VERBATIM>');
			lines.push(indent(11) + `<L-5 L="EN">sample annotation ${id}</L-5>`);
			lines.push(indent(10) + '</VERBATIM>');
			lines.push(indent(9) + '</ANNOTATION-TEXT>');
			lines.push(indent(8) + '</ANNOTATION>');
			lines.push(indent(7) + '</ANNOTATIONS>');
		}
		if (at % 40 === 0) {
			lines.push(indent(7) + '<VARIATION-POINT>');
			lines.push(indent(8) + `<SW-SYSCOND>${id} == ENABLED</SW-SYSCOND>`);
			lines.push(indent(7) + '</VARIATION-POINT>');
		}
		lines.push(indent(7) + '<PARAMETER-VALUES>');
		for (let index = 0; index < paramsPer; index++) {
			const parameter = PARAMS[index];
			if (!parameter) {
				throw new Error(`No sample parameter descriptor at index ${index}`);
			}
			lines.push(...parameterXml(id, parameter, index));
		}
		lines.push(indent(7) + '</PARAMETER-VALUES>');
		if (containers > 1) {
			const target = at === containers ? 'Cont0001' : `Cont${String(at + 1).padStart(4, '0')}`;
			lines.push(indent(7) + '<REFERENCE-VALUES>');
			lines.push(indent(8) + '<ECUC-REFERENCE-VALUE>');
			lines.push(
				indent(9) +
					`<DEFINITION-REF DEST="ECUC-REFERENCE-DEF">/PkgSample/DemoDefs/DemoMod/${id}/Next</DEFINITION-REF>`
			);
			lines.push(
				indent(9) + `<VALUE-REF DEST="ECUC-CONTAINER-VALUE">/PkgSample/DemoMod/${target}</VALUE-REF>`
			);
			lines.push(indent(8) + '</ECUC-REFERENCE-VALUE>');
			lines.push(indent(7) + '</REFERENCE-VALUES>');
		}
		lines.push(indent(6) + '</ECUC-CONTAINER-VALUE>');
	}

	lines.push(indent(5) + '</CONTAINERS>');
	lines.push(indent(4) + '</ECUC-MODULE-CONFIGURATION-VALUES>');
	lines.push(indent(3) + '</ELEMENTS>');
	lines.push(indent(2) + '</AR-PACKAGE>');
	lines.push(indent(1) + '</AR-PACKAGES>');
	lines.push('</AUTOSAR>');
	return lines.join('\n') + '\n';
}

function write(name, content, description, nodeCount) {
	fs.writeFileSync(path.join(ARXML_OUT, name), content, 'utf8');
	const bytes = Buffer.byteLength(content, 'utf8');
	console.log(`${name.padEnd(22)} ${String(nodeCount).padStart(6)} nodes  ${(bytes / 1024).toFixed(1)} KiB  ${description}`);
	return { name, bytes, nodeCount, description };
}

function main() {
	const relative = path.relative(ROOT, OUT);
	const insideRepo =
		relative === '' ||
		(!path.isAbsolute(relative) && relative !== '..' && !relative.startsWith('..' + path.sep));
	if (insideRepo) {
		throw new Error(
			'Refusing to write samples inside the repository (' +
				OUT +
				').\nThe generated files are synthetic build products and must stay outside the repository.'
		);
	}
	fs.mkdirSync(ARXML_OUT, { recursive: true });
	console.log('Generating synthetic ECUC samples in ' + OUT);
	const rows = [];
	rows.push(write('minimal.arxml', moduleXml({ containers: 1, paramsPer: 1 }), 'one module/container/parameter', 3));
	rows.push(
		write(
			'display-rules.arxml',
			fs.readFileSync(path.join(FIXTURES, 'editor', 'render.arxml'), 'utf8'),
			'one instance of every display rule',
			9
		)
	);
	rows.push(
		write(
			'references.arxml',
			fs.readFileSync(path.join(FIXTURES, 'editor', 'navigation.arxml'), 'utf8'),
			'resolvable, ambiguous and missing references',
			11
		)
	);
	rows.push(
		write(
			'deep.arxml',
			fs.readFileSync(path.join(FIXTURES, 'deep.arxml'), 'utf8'),
			'six-level container nesting',
			7
		)
	);
	const large = moduleXml({ containers: 400, paramsPer: 8 });
	rows.push(write('large.arxml', large, '400 containers x 8 parameters + references', 1 + 400 + 3200 + 400));
	const huge = moduleXml({ containers: 1000, paramsPer: 10 });
	rows.push(write('huge.arxml', huge, '1000 containers x 10 parameters + references', 1 + 1000 + 10000 + 1000));

	const readme = [
		'# Synthetic ECUC samples',
		'',
		'These files are generated by `scripts/generate-samples.js` in the `vscode-arxml-scope`',
		'repository. They contain **synthetic data only**; do not treat them as customer files.',
		'They live outside the repository and are not committed. The generator refuses an output',
		'path inside the repository.',
		'',
		'Regenerate with:',
		'',
		'```',
		'npm run samples:ecuc',
		'```',
		'',
		'| File | Approx. nodes | Purpose |',
		'|---|---:|---|',
		...rows.map((row) => `| \`arxml/${row.name}\` | ${row.nodeCount} | ${row.description} |`),
		'',
		'## Manual check',
		'',
		'Open a file in `arxml/` in VS Code and run **ARXML Scope: Open with ECUC Editor** (or use *Open With…*).',
		'`arxml/large.arxml` and `arxml/huge.arxml` are the performance files; use `npm run perf:ecuc -- <file>`',
		'for scanner/renderer timings and the preview harness (`npm run preview:ecuc`) to view them in a',
		'browser. The harness lists this directory as `sample/arxml/<name>` when it exists.',
		'',
		'## Performance is measured, not promised',
		'',
		'The benchmark covers the scanner, node index and renderer in Node. A real VS Code webview also',
		'pays layout and paint costs; the browser harness page load is a separate observation. Do not add',
		'virtualisation from one sample run.',
		'',
	].join('\n');
	fs.writeFileSync(path.join(OUT, 'README.md'), readme, 'utf8');
	console.log('\nREADME.md written.');
	console.log('Done. These files are outside the repository and are not committed.');
}

try {
	main();
} catch (error) {
	console.error('samples: ' + (error && error.message ? error.message : String(error)));
	process.exitCode = 1;
}
